import fs from "node:fs";
import path from "node:path";
import { PROJECT_ROOT, ensureDir, readJson, runDir } from "../src/core/paths.js";

const runs = [
  "arc-real",
  "pulse-real",
  "orbit-real",
  "todopa-bench",
  "studio-test",
  "layout-demo",
];
const outDir = ensureDir(path.join(PROJECT_ROOT, "docs", "qa"));

for (const runId of runs) {
  const source = path.join(runDir(runId), "qa.md");
  if (!fs.existsSync(source)) continue;
  let text = fs.readFileSync(source, "utf8");
  text = text.split(`${PROJECT_ROOT}${path.sep}`).join("");
  text = text.split(PROJECT_ROOT).join("");
  text = `> Generated by \`pnpm qa\`. Paths are relative to the run directory.\n\n${text}`;
  fs.writeFileSync(path.join(outDir, `${runId}.md`), text, "utf8");
}

const fixFile = path.join(runDir("overflow-demo"), "fix.json");
if (fs.existsSync(fixFile)) {
  const fix = readJson<{
    scoreBefore: number;
    scoreAfter: number;
    patches: unknown[];
    skipped: unknown[];
  }>(fixFile);
  fs.writeFileSync(
    path.join(outDir, "fix-loop.json"),
    `${JSON.stringify(
      {
        fixture: "examples/plan-overflow.json",
        scoreBefore: fix.scoreBefore,
        scoreAfter: fix.scoreAfter,
        patches: fix.patches,
        skipped: fix.skipped,
      },
      null,
      2,
    )}\n`,
    "utf8",
  );

  fs.writeFileSync(
    path.join(outDir, "fix-loop.md"),
    [
      "# Fix loop evidence",
      "",
      "Fixture: `examples/plan-overflow.json`",
      "",
      "- Before: 95/100 with a 45px headline overflow (`dom_overflow`).",
      "- Patch: replace `scenes.0.fit` with `{ \"headlineScale\": 1.08 }`.",
      "- After: 100/100, 0 issues.",
      "- The original and fixed renders are kept separately in `runs/overflow-demo/out/video.mp4` and `video.fixed.mp4` (runs/ is gitignored).",
      "",
      "Reproduce:",
      "",
      "```bash",
      "pnpm run render -- --plan examples/plan-overflow.json",
      "pnpm run qa -- --run overflow-demo",
      "pnpm run fix -- --run overflow-demo",
      "```",
      "",
    ].join("\n"),
    "utf8",
  );
}

console.log(`QA evidence written to ${outDir}`);
